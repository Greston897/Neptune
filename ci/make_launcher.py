"""Generate the adaptive launcher icon from the upstream Lucide `orbit` glyph.

Adaptive icon geometry
----------------------
The foreground canvas is 108x108dp. A launcher applies a mask whose visible circle is ~72dp across,
and Android's guaranteed safe zone is a 66dp circle in the middle. The previous artwork filled 52dp
(72% of the visible circle) which read as oversized; the glyph is now sized by its *ink* extent
(stroke included) to GLYPH_DP, so it sits comfortably inside the safe zone at any mask shape.

The glyph is placed by its measured ink centre, not by the viewBox centre, so it is optically
centred on the tile.
"""
import xml.etree.ElementTree as ET
from pathlib import Path

from icon_metrics import _flatten, ink_box

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "ci/launcher/orbit.svg"
RES = ROOT / "app/src/main/res"

CANVAS = 108.0      # adaptive foreground canvas, dp
GLYPH_DP = 42.0     # ink extent of the glyph, stroke included
SAFE_RADIUS = 33.0  # Android's 66dp safe-zone circle


def shapes(root):
    """Yield (kind, attrib) for every stroked shape, in document order."""
    for el in root.iter():
        tag = el.tag.split("}")[-1]
        if tag in ("path", "circle", "line", "polyline", "polygon", "rect"):
            yield tag, el.attrib


def circle_path(cx, cy, r):
    return (f"M{cx-r} {cy}A{r} {r} 0 1 0 {cx+r} {cy}"
            f"A{r} {r} 0 1 0 {cx-r} {cy}Z")


def path_data(tag, a):
    if tag == "path":
        return a["d"]
    if tag == "circle":
        return circle_path(float(a["cx"]), float(a["cy"]), float(a["r"]))
    if tag == "line":
        return f"M{a['x1']} {a['y1']}L{a['x2']} {a['y2']}"
    if tag in ("polyline", "polygon"):
        v = [float(t) for t in a["points"].replace(",", " ").split()]
        pts = list(zip(v[::2], v[1::2]))
        d = "M" + " L".join(f"{x} {y}" for x, y in pts)
        return d + (" Z" if tag == "polygon" else "")
    if tag == "rect":
        x, y = float(a.get("x", 0)), float(a.get("y", 0))
        w, h = float(a["width"]), float(a["height"])
        return f"M{x} {y}H{x+w}V{y+h}H{x}Z"
    raise ValueError(tag)


def build():
    root = ET.parse(SRC).getroot()
    stroke = float(root.attrib.get("stroke-width", 2))
    x0, y0, x1, y1 = ink_box(SRC)
    # Ink extent includes half the stroke on every side.
    ink_w = (x1 - x0) + stroke
    ink_h = (y1 - y0) + stroke
    ink_cx = (x0 + x1) / 2
    ink_cy = (y0 + y1) / 2

    scale = GLYPH_DP / max(ink_w, ink_h)
    tx = CANVAS / 2 - ink_cx * scale
    ty = CANVAS / 2 - ink_cy * scale

    # Sanity: the whole inked glyph must fit inside the guaranteed safe zone.
    half = max(ink_w, ink_h) * scale / 2
    reach = half * (2 ** 0.5)  # worst case: a corner of the ink box
    assert half <= SAFE_RADIUS, f"glyph radius {half:.2f}dp exceeds safe zone {SAFE_RADIUS}dp"

    lines = [
        '<?xml version="1.0" encoding="utf-8"?>',
        '<!-- Generated by ci/make_launcher.py from Lucide `orbit` (ISC). Do not edit by hand. -->',
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
        f'    android:width="{CANVAS:.0f}dp" android:height="{CANVAS:.0f}dp"',
        f'    android:viewportWidth="{CANVAS:.0f}" android:viewportHeight="{CANVAS:.0f}">',
        f'    <group android:name="glyph" android:translateX="{tx:.4f}" android:translateY="{ty:.4f}"',
        f'        android:scaleX="{scale:.6f}" android:scaleY="{scale:.6f}">',
    ]
    for tag, a in shapes(root):
        lines += [
            f'        <path android:pathData="{path_data(tag, a)}"',
            '            android:strokeColor="#FFFFFFFF"',
            f'            android:strokeWidth="{stroke:g}"',
            '            android:strokeLineCap="round" android:strokeLineJoin="round"',
            '            android:fillColor="#00000000" />',
        ]
    lines += ["    </group>", "</vector>", ""]
    (RES / "drawable/ic_launcher_foreground.xml").write_text("\n".join(lines))

    (RES / "drawable/ic_launcher_background.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        '<!-- Generated by ci/make_launcher.py. Pure black, no gradient. -->\n'
        '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">\n'
        '    <solid android:color="#000000" />\n'
        '</shape>\n'
    )

    # Monochrome layer (Android 13 themed icons) reuses the same centred glyph.
    (RES / "drawable/ic_launcher_monochrome.xml").write_text(
        (RES / "drawable/ic_launcher_foreground.xml").read_text()
        .replace("from Lucide `orbit` (ISC). Do not edit by hand.",
                 "from Lucide `orbit` (ISC); monochrome layer for themed icons.")
    )
    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        (RES / "mipmap-anydpi-v26" / name).write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
            '</adaptive-icon>\n'
        )

    print(f"launcher: glyph {GLYPH_DP:g}dp ink on {CANVAS:g}dp canvas "
          f"({GLYPH_DP / 72 * 100:.0f}% of the visible circle), "
          f"centre ({CANVAS/2:g},{CANVAS/2:g}), scale {scale:.4f}, "
          f"corner reach {reach:.1f}dp <= safe {SAFE_RADIUS:g}dp")


if __name__ == "__main__":
    build()
